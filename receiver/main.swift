// MN Agent Bridge Receiver
//
// A tiny background-only macOS app that owns the `mnagentbridge://` URL scheme.
// The MarginNote add-on answers every request by opening
//   mnagentbridge://result?id=<requestId>&part=<i>&total=<n>&payload=<url-encoded JSON>
// and this app writes each part to ~/.mn-agent-bridge/inbox/<requestId>.<part>-of-<total>.json,
// where the CLI / MCP server picks it up. It never shows UI and quits after a short idle period.

import AppKit
import Foundation

final class Receiver: NSObject, NSApplicationDelegate {
    private var idleTimer: Timer?
    private let inbox: URL = {
        let home = FileManager.default.homeDirectoryForCurrentUser
        return home.appendingPathComponent(".mn-agent-bridge/inbox", isDirectory: true)
    }()

    func applicationWillFinishLaunching(_ notification: Notification) {
        NSAppleEventManager.shared().setEventHandler(
            self,
            andSelector: #selector(handleGetURL(_:withReplyEvent:)),
            forEventClass: AEEventClass(kInternetEventClass),
            andEventID: AEEventID(kAEGetURL)
        )
    }

    func applicationDidFinishLaunching(_ notification: Notification) {
        armIdleTimer()
    }

    @objc func handleGetURL(_ event: NSAppleEventDescriptor, withReplyEvent reply: NSAppleEventDescriptor) {
        defer { armIdleTimer() }
        guard let raw = event.paramDescriptor(forKeyword: keyDirectObject)?.stringValue,
              let comps = URLComponents(string: raw),
              comps.scheme == "mnagentbridge" else { return }

        var query: [String: String] = [:]
        for item in comps.queryItems ?? [] { query[item.name] = item.value ?? "" }

        // Request ids are generated by the CLI; keep them filesystem-safe.
        guard let id = query["id"], !id.isEmpty,
              id.range(of: "^[A-Za-z0-9_-]{1,80}$", options: .regularExpression) != nil else { return }
        let part = Int(query["part"] ?? "0") ?? 0
        let total = Int(query["total"] ?? "1") ?? 1
        let payload = query["payload"] ?? ""

        do {
            try FileManager.default.createDirectory(at: inbox, withIntermediateDirectories: true,
                                                    attributes: [.posixPermissions: 0o700])
            let name = "\(id).\(part)-of-\(total).json"
            let tmp = inbox.appendingPathComponent(".\(name).tmp")
            try payload.write(to: tmp, atomically: false, encoding: .utf8)
            // Rename last so readers never see a half-written file.
            let dest = inbox.appendingPathComponent(name)
            try? FileManager.default.removeItem(at: dest)
            try FileManager.default.moveItem(at: tmp, to: dest)
        } catch {
            NSLog("MNAgentBridgeReceiver: failed to write result: \(error)")
        }
    }

    private func armIdleTimer() {
        idleTimer?.invalidate()
        idleTimer = Timer.scheduledTimer(withTimeInterval: 20, repeats: false) { _ in
            NSApp.terminate(nil)
        }
    }
}

let app = NSApplication.shared
let delegate = Receiver()
app.delegate = delegate
app.setActivationPolicy(.prohibited)
app.run()
