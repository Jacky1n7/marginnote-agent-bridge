#!/usr/bin/env node
// Build the MarginNote add-on and everything generated from its action registry:
//   dist/addon/{main.js,mnaddon.json,logo.png}   unpacked add-on
//   dist/MNAgentBridge-v<version>.mnaddon         installable package
//   cli/lib/actions.json                           registry used by the CLI and MCP server
//   docs/API.md                                    action reference
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const version = pkg.version;
const srcDir = path.join(root, 'addon/src');
const distDir = path.join(root, 'dist');
const addonDir = path.join(distDir, 'addon');

const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.js')).sort();
const body = files
  .map((f) => `// ==== ${f} ====\n` + fs.readFileSync(path.join(srcDir, f), 'utf8'))
  .join('\n')
  .replaceAll('__BRIDGE_VERSION__', version);

// 1. Extract the registry by evaluating the modules without native objects.
const sandbox = { console };
vm.createContext(sandbox);
vm.runInContext(body + '\n;globalThis.__registry = { ACTIONS, ACTION_ORDER };', sandbox, { filename: 'addon-bundle.js' });
const { ACTIONS, ACTION_ORDER } = sandbox.__registry;
const actions = ACTION_ORDER.map((name) => {
  const d = ACTIONS[name];
  return {
    name: d.name,
    group: d.group,
    summary: d.summary,
    write: !!d.write,
    public: !!d.public,
    async: !!d.async,
    experimental: !!d.experimental,
    params: d.params || {},
    returns: d.returns || null,
  };
});

// 2. Bundle the add-on.
const mainJs = [
  '// MN Agent Bridge v' + version + ' — https://github.com/Jacky1n7/marginnote-agent-bridge',
  '// Generated by scripts/build.mjs from addon/src. Do not edit by hand.',
  'JSB.newAddon = function (mainPath) {',
  body,
  'return defineAddonClass();',
  '};',
  '',
].join('\n');
new vm.Script(mainJs, { filename: 'main.js' }); // syntax check

fs.rmSync(addonDir, { recursive: true, force: true });
fs.mkdirSync(addonDir, { recursive: true });
fs.writeFileSync(path.join(addonDir, 'main.js'), mainJs);
fs.writeFileSync(
  path.join(addonDir, 'mnaddon.json'),
  JSON.stringify(
    {
      addonid: 'io.github.jacky1n7.agentbridge',
      author: 'Jacky1n7',
      title: 'MN Agent Bridge',
      version,
      marginnote_version_min: '4.0.0',
      cert_key: '',
    },
    null,
    2,
  ) + '\n',
);
fs.copyFileSync(path.join(root, 'assets/logo.png'), path.join(addonDir, 'logo.png'));

const pkgName = `MNAgentBridge-v${version}.mnaddon`;
for (const f of fs.readdirSync(distDir)) if (f.endsWith('.mnaddon')) fs.rmSync(path.join(distDir, f));
execFileSync('zip', ['-j', '-q', path.join(distDir, pkgName), 'main.js', 'mnaddon.json', 'logo.png'].map((x, i) => (i < 3 ? x : path.join(addonDir, x))), {
  stdio: 'inherit',
});

// 3. Registry for the CLI / MCP server.
fs.writeFileSync(path.join(root, 'cli/lib/actions.json'), JSON.stringify({ version, actions }, null, 2) + '\n');

// 4. API reference.
fs.writeFileSync(path.join(root, 'docs/API.md'), renderApiDoc(actions));

console.log(`built ${pkgName} with ${actions.length} actions`);

function renderApiDoc(list) {
  const groups = [];
  for (const a of list) {
    let g = groups.find((x) => x.name === a.group);
    if (!g) groups.push((g = { name: a.group, items: [] }));
    g.items.push(a);
  }
  const titles = {
    system: 'System & pairing', context: 'Context', ui: 'UI & commands', notebooks: 'Notebooks',
    documents: 'Documents', notes: 'Notes (cards)', comments: 'Comments', tags: 'Tags', review: 'Review', batch: 'Batch',
  };
  const out = [];
  out.push('# API reference', '');
  out.push(`> Generated from the add-on's action registry (v${version}). Do not edit by hand — run \`npm run build\`.`, '');
  out.push('Every action is called the same way — from the CLI, from the MCP server (tool name = action name with `.` → `_`), or as a raw URL:', '');
  out.push('```bash', 'mnab call note.get \'{"noteId":"…"}\'', '```', '');
  out.push('Legend: ✏️ writes data (one undo step) · 🔓 no token needed · 🧪 experimental', '');
  out.push('## Contents', '');
  for (const g of groups) {
    out.push(`- **${titles[g.name] || g.name}**: ` + g.items.map((a) => `[\`${a.name}\`](#${a.name.replace(/\./g, '')})`).join(' · '));
  }
  out.push('');
  for (const g of groups) {
    out.push(`## ${titles[g.name] || g.name}`, '');
    for (const a of g.items) {
      const badges = [a.write ? '✏️' : '', a.public ? '🔓' : '', a.experimental ? '🧪' : ''].filter(Boolean).join(' ');
      out.push(`### \`${a.name}\` ${badges}`.trimEnd(), '');
      out.push(a.summary, '');
      const params = Object.entries(a.params);
      if (params.length) {
        out.push('| Parameter | Type | Required | Default | Description |', '| --- | --- | --- | --- | --- |');
        for (const [k, s] of params) {
          const type = s.type + (s.items ? `<${s.items}>` : '') + (s.enum ? ` (${s.enum.join(' \\| ')})` : '');
          const def = s.default === undefined ? '' : '`' + JSON.stringify(s.default) + '`';
          out.push(`| \`${k}\` | ${type} | ${s.required ? 'yes' : ''} | ${def} | ${(s.desc || '').replace(/\|/g, '\\|')} |`);
        }
        out.push('');
      } else {
        out.push('_No parameters._', '');
      }
      if (a.returns) out.push(`**Returns:** \`${a.returns}\``, '');
    }
  }
  return out.join('\n');
}
